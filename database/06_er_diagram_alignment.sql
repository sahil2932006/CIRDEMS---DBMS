-- Additive migration to align the operational schema with the supplied ER diagram.
-- Existing seed/application tables are retained; these changes preserve their data.

ALTER TABLE USERS ADD (username VARCHAR2(80));
UPDATE USERS
SET username = LOWER(REGEXP_REPLACE(first_name || '.' || last_name || '.' || TO_CHAR(user_id), '[^A-Za-z0-9._-]', ''));
ALTER TABLE USERS MODIFY (username NOT NULL);
ALTER TABLE USERS ADD CONSTRAINT uq_users_username UNIQUE (username);

-- The ER diagram permits one incident to have multiple investigations.
ALTER TABLE INVESTIGATIONS DROP CONSTRAINT uq_inv_incident;

-- Response actions belong to incidents and may be assigned to a user.
ALTER TABLE RESPONSE_ACTIONS ADD (
    incident_id NUMBER(10),
    assigned_to NUMBER(10),
    action_date TIMESTAMP
);
UPDATE RESPONSE_ACTIONS a
SET (incident_id, assigned_to, action_date) = (
    SELECT i.incident_id, a.performed_by, a.executed_at
    FROM INVESTIGATIONS i
    WHERE i.investigation_id = a.investigation_id
);
ALTER TABLE RESPONSE_ACTIONS MODIFY (incident_id NOT NULL, investigation_id NULL);
ALTER TABLE RESPONSE_ACTIONS ADD CONSTRAINT fk_action_incident
    FOREIGN KEY (incident_id) REFERENCES INCIDENTS(incident_id);
ALTER TABLE RESPONSE_ACTIONS ADD CONSTRAINT fk_action_assignee
    FOREIGN KEY (assigned_to) REFERENCES USERS(user_id);

-- Evidence is connected directly to its incident; the investigation reference
-- remains as project history for the existing forensic workflow.
ALTER TABLE EVIDENCE ADD (
    incident_id NUMBER(10),
    source VARCHAR2(80),
    file_path VARCHAR2(200),
    notes VARCHAR2(400)
);
BEGIN
    EXECUTE IMMEDIATE 'ALTER TRIGGER TRG_PREVENT_EVIDENCE_TAMPERING DISABLE';
    BEGIN
        UPDATE EVIDENCE e
        SET (incident_id, source, file_path, notes) = (
            SELECT i.incident_id, e.acquisition_method, e.storage_location, e.description
            FROM INVESTIGATIONS i
            WHERE i.investigation_id = e.investigation_id
        );
        MERGE INTO EVIDENCE e
        USING (
            SELECT ROWID AS evidence_rowid,
                   ROW_NUMBER() OVER (ORDER BY investigation_id, evidence_id) AS new_evidence_id
            FROM EVIDENCE
        ) ids
        ON (e.ROWID = ids.evidence_rowid)
        WHEN MATCHED THEN UPDATE SET e.evidence_id = ids.new_evidence_id;
    EXCEPTION
        WHEN OTHERS THEN
            EXECUTE IMMEDIATE 'ALTER TRIGGER TRG_PREVENT_EVIDENCE_TAMPERING ENABLE';
            RAISE;
    END;
    EXECUTE IMMEDIATE 'ALTER TRIGGER TRG_PREVENT_EVIDENCE_TAMPERING ENABLE';
END;
/
ALTER TABLE EVIDENCE MODIFY (incident_id NOT NULL);
ALTER TABLE EVIDENCE DROP CONSTRAINT pk_evidence;
ALTER TABLE EVIDENCE ADD CONSTRAINT pk_evidence PRIMARY KEY (evidence_id);
ALTER TABLE EVIDENCE MODIFY (investigation_id NULL);
ALTER TABLE EVIDENCE ADD CONSTRAINT fk_evi_incident
    FOREIGN KEY (incident_id) REFERENCES INCIDENTS(incident_id);
DECLARE
    v_next_id NUMBER;
BEGIN
    SELECT NVL(MAX(evidence_id), 0) + 1 INTO v_next_id FROM EVIDENCE;
    EXECUTE IMMEDIATE 'CREATE SEQUENCE seq_evidence_id START WITH ' || v_next_id || ' INCREMENT BY 1 NOCACHE';
END;
/

-- Vulnerabilities belong to incidents. Historical rows without a matching
-- incident remain available and can be linked from the website later.
ALTER TABLE VULNERABILITIES ADD (incident_id NUMBER(10));
UPDATE VULNERABILITIES v
SET incident_id = (
    SELECT MIN(i.incident_id) FROM INCIDENTS i WHERE i.asset_id = v.asset_id
)
WHERE EXISTS (SELECT 1 FROM INCIDENTS i WHERE i.asset_id = v.asset_id);
ALTER TABLE VULNERABILITIES ADD CONSTRAINT fk_vuln_incident
    FOREIGN KEY (incident_id) REFERENCES INCIDENTS(incident_id);

CREATE TABLE REPORTS (
    report_id      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    incident_id    NUMBER(10) NOT NULL,
    report_type    VARCHAR2(80) NOT NULL,
    date_generated TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    summary        VARCHAR2(2000),
    generated_by   NUMBER(10),
    CONSTRAINT pk_reports PRIMARY KEY (report_id),
    CONSTRAINT fk_reports_incident FOREIGN KEY (incident_id) REFERENCES INCIDENTS(incident_id) ON DELETE CASCADE,
    CONSTRAINT fk_reports_user FOREIGN KEY (generated_by) REFERENCES USERS(user_id) ON DELETE SET NULL
);

CREATE TABLE CHAIN_OF_CUSTODY (
    log_id          NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    evidence_id     NUMBER(10) NOT NULL,
    handled_by      NUMBER(10) NOT NULL,
    action_detail   VARCHAR2(200) NOT NULL,
    action_time     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    location        VARCHAR2(200),
    remarks         VARCHAR2(1000),
    CONSTRAINT pk_chain_of_custody PRIMARY KEY (log_id),
    CONSTRAINT fk_custody_evidence FOREIGN KEY (evidence_id)
        REFERENCES EVIDENCE(evidence_id) ON DELETE CASCADE,
    CONSTRAINT fk_custody_user FOREIGN KEY (handled_by) REFERENCES USERS(user_id)
);

CREATE INDEX ix_action_incident ON RESPONSE_ACTIONS(incident_id);
CREATE INDEX ix_evidence_incident ON EVIDENCE(incident_id);
CREATE INDEX ix_vulnerability_incident ON VULNERABILITIES(incident_id);
CREATE INDEX ix_reports_incident ON REPORTS(incident_id);
CREATE INDEX ix_custody_evidence ON CHAIN_OF_CUSTODY(evidence_id);

COMMIT;
