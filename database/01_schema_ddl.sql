BEGIN
    FOR c IN (SELECT table_name FROM user_tables WHERE table_name IN (
        'CHAIN_OF_CUSTODY', 'REPORTS', 'RESPONSE_ACTIONS', 'INDICATORS', 'EVIDENCE', 'INVESTIGATIONS',
        'ALERTS', 'INCIDENTS', 'VULNERABILITIES', 'ASSETS', 'USER_PHONES', 'USERS'
    )) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || c.table_name || ' CASCADE CONSTRAINTS PURGE';
