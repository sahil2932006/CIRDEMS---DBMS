-- ----------------------------------------------------------------------------
-- TABLE 1: USERS (Strong Entity)
-- Composite Name: first_name, middle_name, last_name
-- Composite Address: street, city, state, pincode
-- ----------------------------------------------------------------------------
CREATE TABLE USERS (
    user_id          NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    first_name       VARCHAR2(50) NOT NULL,
    middle_name      VARCHAR2(50),
    last_name        VARCHAR2(50) NOT NULL,
    email            VARCHAR2(100) NOT NULL,
    role             VARCHAR2(30) NOT NULL,
    department       VARCHAR2(60) NOT NULL,
    job_title        VARCHAR2(60) NOT NULL,
    street           VARCHAR2(100),
    city             VARCHAR2(50),
    state            VARCHAR2(50),
    pincode          VARCHAR2(15),
    date_joined      DATE DEFAULT SYSDATE NOT NULL,
    account_status   VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (user_id),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT chk_users_role CHECK (role IN (
        'SOC_ANALYST', 'INCIDENT_RESPONDER', 'FORENSIC_EXAMINER',
        'SYSTEM_ADMIN', 'SECURITY_MANAGER', 'STANDARD_USER'
    )),
    CONSTRAINT chk_users_status CHECK (account_status IN ('ACTIVE', 'SUSPENDED', 'DEACTIVATED'))
);

-- ----------------------------------------------------------------------------
-- TABLE 2: USER_PHONES (Normalized Multivalued Attribute)
-- ----------------------------------------------------------------------------
CREATE TABLE USER_PHONES (
    user_id          NUMBER(10) NOT NULL,
    phone_number     VARCHAR2(20) NOT NULL,
    phone_type       VARCHAR2(15) DEFAULT 'MOBILE' NOT NULL,
    CONSTRAINT pk_user_phones PRIMARY KEY (user_id, phone_number),
    CONSTRAINT fk_uphones_user FOREIGN KEY (user_id) REFERENCES USERS(user_id) ON DELETE CASCADE,
    CONSTRAINT chk_uphones_type CHECK (phone_type IN ('MOBILE', 'WORK_DESK', 'ON_CALL_PAGER'))
);

-- ----------------------------------------------------------------------------
-- TABLE 3: ASSETS (Strong Entity)
-- ----------------------------------------------------------------------------
CREATE TABLE ASSETS (
    asset_id         NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    asset_name       VARCHAR2(80) NOT NULL,
    asset_type       VARCHAR2(40) NOT NULL,
    ip_address       VARCHAR2(45) NOT NULL,
    mac_address      VARCHAR2(17) NOT NULL,
    operating_system VARCHAR2(50) NOT NULL,
    os_version       VARCHAR2(30),
    location         VARCHAR2(80) NOT NULL,
    criticality      VARCHAR2(20) DEFAULT 'MEDIUM' NOT NULL,
    owner_user_id    NUMBER(10),
    purchase_date    DATE,
    last_scan_date   DATE DEFAULT SYSDATE,
    asset_status     VARCHAR2(30) DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT pk_assets PRIMARY KEY (asset_id),
    CONSTRAINT uq_assets_mac UNIQUE (mac_address),
    CONSTRAINT fk_assets_owner FOREIGN KEY (owner_user_id) REFERENCES USERS(user_id) ON DELETE SET NULL,
    CONSTRAINT chk_assets_criticality CHECK (criticality IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT chk_assets_status CHECK (asset_status IN (
        'ACTIVE', 'UNDER_INVESTIGATION', 'COMPROMISED', 'ISOLATED', 'DECOMMISSIONED'
    )),
    CONSTRAINT chk_assets_type CHECK (asset_type IN (
        'Workstation', 'Database Server', 'Web Server', 'Firewall', 'Core Router', 'Domain Controller'
    ))
);

-- ----------------------------------------------------------------------------
-- TABLE 4: VULNERABILITIES (Strong Entity)
-- ----------------------------------------------------------------------------
CREATE TABLE VULNERABILITIES (
    vulnerability_id     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    asset_id             NUMBER(10) NOT NULL,
    cve_code             VARCHAR2(25) NOT NULL,
    vulnerability_title  VARCHAR2(150) NOT NULL,
    description          VARCHAR2(500) NOT NULL,
    severity             VARCHAR2(20) DEFAULT 'MEDIUM' NOT NULL,
    discovered_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    patch_status         VARCHAR2(25) DEFAULT 'OPEN' NOT NULL,
    remediation_deadline DATE NOT NULL,
    affected_version     VARCHAR2(50),
    remediation_notes    VARCHAR2(400),
    CONSTRAINT pk_vulnerabilities PRIMARY KEY (vulnerability_id),
    CONSTRAINT fk_vuln_asset FOREIGN KEY (asset_id) REFERENCES ASSETS(asset_id) ON DELETE CASCADE,
    CONSTRAINT chk_vuln_severity CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT chk_vuln_patch_status CHECK (patch_status IN ('OPEN', 'IN_PROGRESS', 'PATCHED', 'RISK_ACCEPTED'))
);

-- ----------------------------------------------------------------------------
-- TABLE 5: ALERTS (Strong Entity)
-- ----------------------------------------------------------------------------
CREATE TABLE ALERTS (
    alert_id             NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    asset_id             NUMBER(10) NOT NULL,
    vulnerability_id     NUMBER(10),
    alert_type           VARCHAR2(60) NOT NULL,
    alert_message        VARCHAR2(400) NOT NULL,
    severity             VARCHAR2(20) DEFAULT 'MEDIUM' NOT NULL,
    source_system        VARCHAR2(60) NOT NULL,
    confidence_score     NUMBER(3) DEFAULT 50 NOT NULL,
    generated_at         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    alert_status         VARCHAR2(25) DEFAULT 'NEW' NOT NULL,
    detection_rule       VARCHAR2(100),
    acknowledgement_time TIMESTAMP,
    CONSTRAINT pk_alerts PRIMARY KEY (alert_id),
    CONSTRAINT fk_alerts_asset FOREIGN KEY (asset_id) REFERENCES ASSETS(asset_id) ON DELETE CASCADE,
    CONSTRAINT fk_alerts_vuln FOREIGN KEY (vulnerability_id) REFERENCES VULNERABILITIES(vulnerability_id) ON DELETE SET NULL,
    CONSTRAINT chk_alerts_severity CHECK (severity IN ('INFO', 'LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT chk_alerts_confidence CHECK (confidence_score BETWEEN 0 AND 100),
    CONSTRAINT chk_alerts_status CHECK (alert_status IN ('NEW', 'ACKNOWLEDGED', 'ESCALATED', 'FALSE_POSITIVE', 'SUPPRESSED'))
);

-- ----------------------------------------------------------------------------
-- TABLE 6: INCIDENTS (Strong Entity)
-- ----------------------------------------------------------------------------
CREATE TABLE INCIDENTS (
    incident_id          NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    asset_id             NUMBER(10) NOT NULL,
    reporter_user_id     NUMBER(10) NOT NULL,
    incident_title       VARCHAR2(150) NOT NULL,
    incident_type        VARCHAR2(60) NOT NULL,
    severity             VARCHAR2(20) DEFAULT 'MEDIUM' NOT NULL,
    description          VARCHAR2(1000) NOT NULL,
    detected_at          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    reported_at          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    status               VARCHAR2(25) DEFAULT 'DETECTED' NOT NULL,
    resolved_at          TIMESTAMP,
    source               VARCHAR2(60) NOT NULL,
    impact_level         VARCHAR2(20) DEFAULT 'MODERATE' NOT NULL,
    resolution_summary   VARCHAR2(1000),
    CONSTRAINT pk_incidents PRIMARY KEY (incident_id),
    CONSTRAINT fk_inc_asset FOREIGN KEY (asset_id) REFERENCES ASSETS(asset_id),
    CONSTRAINT fk_inc_reporter FOREIGN KEY (reporter_user_id) REFERENCES USERS(user_id),
    CONSTRAINT chk_inc_severity CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT chk_inc_impact CHECK (impact_level IN ('MINOR', 'MODERATE', 'MAJOR', 'CATASTROPHIC')),
    CONSTRAINT chk_inc_status CHECK (status IN ('DETECTED', 'INVESTIGATING', 'CONTAINED', 'RESOLVED', 'CLOSED')),
    CONSTRAINT chk_inc_timestamps CHECK (resolved_at IS NULL OR resolved_at >= detected_at)
);

-- ----------------------------------------------------------------------------
-- TABLE 7: INVESTIGATIONS (Strong Entity, 1:1 with INCIDENTS via UNIQUE)
-- ----------------------------------------------------------------------------
CREATE TABLE INVESTIGATIONS (
    investigation_id      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    incident_id           NUMBER(10) NOT NULL,
    lead_user_id          NUMBER(10),
    start_time            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    end_time              TIMESTAMP,
    priority              VARCHAR2(20) DEFAULT 'P3_MEDIUM' NOT NULL,
    investigation_status  VARCHAR2(25) DEFAULT 'OPEN' NOT NULL,
    findings              VARCHAR2(1500),
    investigation_summary VARCHAR2(1000),
    methodology           VARCHAR2(80) NOT NULL,
    conclusion            VARCHAR2(1000),
    created_at            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_investigations PRIMARY KEY (investigation_id),
    CONSTRAINT uq_inv_incident UNIQUE (incident_id),
    CONSTRAINT fk_inv_incident FOREIGN KEY (incident_id) REFERENCES INCIDENTS(incident_id) ON DELETE CASCADE,
    CONSTRAINT fk_inv_lead FOREIGN KEY (lead_user_id) REFERENCES USERS(user_id) ON DELETE SET NULL,
    CONSTRAINT chk_inv_priority CHECK (priority IN ('P1_URGENT', 'P2_HIGH', 'P3_MEDIUM', 'P4_LOW')),
    CONSTRAINT chk_inv_status CHECK (investigation_status IN ('OPEN', 'IN_PROGRESS', 'PENDING_EVIDENCE', 'COMPLETED'))
);

-- ----------------------------------------------------------------------------
-- TABLE 8: EVIDENCE (Weak Entity with Composite Primary Key)
-- ----------------------------------------------------------------------------
CREATE TABLE EVIDENCE (
    investigation_id      NUMBER(10) NOT NULL,
    evidence_id           NUMBER(10) NOT NULL,
    collected_by          NUMBER(10),
    evidence_type         VARCHAR2(50) NOT NULL,
    file_name             VARCHAR2(120) NOT NULL,
    hash_value            CHAR(64) NOT NULL,
    collected_at          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    storage_location      VARCHAR2(200) NOT NULL,
    integrity_status      VARCHAR2(20) DEFAULT 'UNVERIFIED' NOT NULL,
    description           VARCHAR2(400) NOT NULL,
    acquisition_method    VARCHAR2(80) NOT NULL,
    evidence_status       VARCHAR2(25) DEFAULT 'ACQUIRED' NOT NULL,
    CONSTRAINT pk_evidence PRIMARY KEY (investigation_id, evidence_id),
    CONSTRAINT fk_evi_inv FOREIGN KEY (investigation_id) REFERENCES INVESTIGATIONS(investigation_id) ON DELETE CASCADE,
    CONSTRAINT fk_evi_collector FOREIGN KEY (collected_by) REFERENCES USERS(user_id) ON DELETE SET NULL,
    CONSTRAINT chk_evi_integrity CHECK (integrity_status IN ('UNVERIFIED', 'VERIFIED', 'COMPROMISED')),
    CONSTRAINT chk_evi_status CHECK (evidence_status IN ('ACQUIRED', 'ANALYZED', 'ARCHIVED', 'PRESENTED_IN_COURT'))
);

-- ----------------------------------------------------------------------------
-- TABLE 9: INDICATORS (Strong Entity - Threat IOCs)
-- ----------------------------------------------------------------------------
CREATE TABLE INDICATORS (
    indicator_id          NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    incident_id           NUMBER(10) NOT NULL,
    indicator_type        VARCHAR2(30) NOT NULL,
    indicator_value       VARCHAR2(255) NOT NULL,
    first_seen            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    last_seen             TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    confidence            NUMBER(3) DEFAULT 75 NOT NULL,
    source                VARCHAR2(80) NOT NULL,
    status                VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    description           VARCHAR2(400),
    threat_category       VARCHAR2(50) NOT NULL,
    CONSTRAINT pk_indicators PRIMARY KEY (indicator_id),
    CONSTRAINT fk_ind_incident FOREIGN KEY (incident_id) REFERENCES INCIDENTS(incident_id) ON DELETE CASCADE,
    CONSTRAINT chk_ind_confidence CHECK (confidence BETWEEN 0 AND 100),
    CONSTRAINT chk_ind_status CHECK (status IN ('ACTIVE', 'REVOKED', 'EXPIRED')),
    CONSTRAINT chk_ind_type CHECK (indicator_type IN ('IPv4', 'Domain', 'URL', 'SHA256_Hash', 'Registry_Key', 'Email_Subject'))
);

-- ----------------------------------------------------------------------------
-- TABLE 10: RESPONSE_ACTIONS (Strong Entity)
-- ----------------------------------------------------------------------------
CREATE TABLE RESPONSE_ACTIONS (
    action_id             NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    investigation_id      NUMBER(10) NOT NULL,
    performed_by          NUMBER(10),
    action_type           VARCHAR2(60) NOT NULL,
    action_description    VARCHAR2(400) NOT NULL,
    executed_at           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    result                VARCHAR2(25) DEFAULT 'SUCCESS' NOT NULL,
    action_status         VARCHAR2(25) DEFAULT 'COMPLETED' NOT NULL,
    priority              VARCHAR2(20) DEFAULT 'NORMAL' NOT NULL,
    remarks               VARCHAR2(400),
    verification_status   VARCHAR2(20) DEFAULT 'VERIFIED' NOT NULL,
    CONSTRAINT pk_response_actions PRIMARY KEY (action_id),
    CONSTRAINT fk_act_inv FOREIGN KEY (investigation_id) REFERENCES INVESTIGATIONS(investigation_id) ON DELETE CASCADE,
    CONSTRAINT fk_act_user FOREIGN KEY (performed_by) REFERENCES USERS(user_id) ON DELETE SET NULL,
    CONSTRAINT chk_act_result CHECK (result IN ('SUCCESS', 'FAILED', 'PARTIAL_SUCCESS')),
    CONSTRAINT chk_act_status CHECK (action_status IN ('PENDING', 'IN_EXECUTION', 'COMPLETED', 'ABORTED')),
    CONSTRAINT chk_act_priority CHECK (priority IN ('EMERGENCY', 'HIGH', 'NORMAL')),
    CONSTRAINT chk_act_verif CHECK (verification_status IN ('VERIFIED', 'UNVERIFIED'))
);

