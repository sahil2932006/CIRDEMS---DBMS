PROMPT ============================================================================;
PROMPT 2. DEMONSTRATION OF UPDATE OPERATIONS
PROMPT ============================================================================;

-- 2.1 Update Asset Status during Maintenance
PROMPT --- 2.1 Updating Asset Status and Last Scan Date ---;
UPDATE ASSETS
SET asset_status = 'UNDER_INVESTIGATION',
    last_scan_date = SYSDATE
WHERE mac_address = '00:1A:2B:3C:4D:99';

-- 2.2 Update Alert Status upon Analyst Triage
PROMPT --- 2.2 Acknowledging and Escalating Alert ---;
UPDATE ALERTS
SET alert_status = 'ACKNOWLEDGED',
    acknowledgement_time = SYSTIMESTAMP
WHERE asset_id = (SELECT asset_id FROM ASSETS WHERE mac_address = '00:1A:2B:3C:4D:99')
AND alert_status = 'NEW';

-- Check update results
SELECT asset_id, asset_name, asset_status, last_scan_date 
FROM ASSETS 
WHERE mac_address = '00:1A:2B:3C:4D:99';

PROMPT ============================================================================;
PROMPT 3. DEMONSTRATION OF DELETE OPERATIONS & ROLLBACK / COMMIT
PROMPT ============================================================================;

-- 3.1 Attempting to delete verified evidence (will be rejected by Trigger)
PROMPT --- 3.1 Trigger Guard Test: Attempting to delete VERIFIED evidence (Expected to FAIL) ---;
BEGIN
    DELETE FROM EVIDENCE 
    WHERE investigation_id = 1 AND evidence_id = 1;
EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('>>> TRIGGER TRG_PREVENT_EVIDENCE_TAMPERING ENFORCED: ' || SQLERRM);
END;
/

-- 3.2 Safe Delete of an Unverified / Obsolete Temporary Indicator with ROLLBACK
PROMPT --- 3.2 Delete with Transaction Rollback Demonstration ---;
SAVEPOINT sp_before_indicator_delete;

-- Insert temporary indicator
INSERT INTO INDICATORS (
    incident_id, indicator_type, indicator_value, confidence,
    source, status, threat_category
) VALUES (
    5, 'IPv4', '198.51.100.99', 40, 'Ad-hoc Scan', 'ACTIVE', 'Phishing_Drop'
);

SELECT COUNT(*) AS active_indicators_count FROM INDICATORS WHERE indicator_value = '198.51.100.99';

-- Perform DELETE
DELETE FROM INDICATORS WHERE indicator_value = '198.51.100.99';
PROMPT Deleted temporary indicator. Checking row count:;
SELECT COUNT(*) AS count_after_delete FROM INDICATORS WHERE indicator_value = '198.51.100.99';

-- Rollback to demonstrate transaction recovery
ROLLBACK TO sp_before_indicator_delete;
PROMPT Rolled back transaction. Row count restored:;
SELECT COUNT(*) AS count_after_rollback FROM INDICATORS WHERE indicator_value = '198.51.100.99';

-- Clean up test records
DELETE FROM ALERTS WHERE asset_id = (SELECT asset_id FROM ASSETS WHERE mac_address = '00:1A:2B:3C:4D:99');
DELETE FROM ASSETS WHERE mac_address = '00:1A:2B:3C:4D:99';
COMMIT;

