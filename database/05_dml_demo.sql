INSERT INTO ASSETS (
    asset_name, asset_type, ip_address, mac_address, operating_system,
    os_version, location, criticality, owner_user_id, purchase_date, asset_status
) VALUES (
    'FW-BRANCH-OFFICE', 'Firewall', '192.168.10.1', '00:1A:2B:3C:4D:99', 'Palo Alto PAN-OS',
    '10.2.6', 'Branch Office - Bangalore', 'HIGH', 9, DATE '2024-01-10', 'ACTIVE'
);

-- 1.2 Insert an Associated Security Alert
PROMPT --- 1.2 Inserting Alert generated by Branch Firewall ---;
INSERT INTO ALERTS (
    asset_id, alert_type, alert_message, severity, source_system,
    confidence_score, alert_status, detection_rule
) VALUES (
    (SELECT asset_id FROM ASSETS WHERE mac_address = '00:1A:2B:3C:4D:99'),
